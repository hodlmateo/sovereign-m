#!/usr/bin/env python3
"""Regenerate src/pytables.rs from the *running* Python interpreter.

Rust's `regex` and Python's `re` disagree on which characters are word
characters (marks, Unicode-version drift, No/Nl) and on a few case-folding
relatives (e.g. dotless i, long s). cmdguard normalises text before regex
matching using the tables this script emits, so Rust classifies text the way
Python does. Re-run after upgrading Python or the Rust toolchain; the test
suite fails if the checked-in file is stale.

    python3 rust/cmdguard/tools/gen_pytables.py [path/to/cmdguard-rs]
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "pytables.rs"


def ranges(points):
    out, start, prev = [], None, None
    for p in points:
        if start is None:
            start = prev = p
        elif p == prev + 1:
            prev = p
        else:
            out.append((start, prev))
            start = prev = p
    if start is not None:
        out.append((start, prev))
    return out


def py_word_points():
    pts = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        if c.isalnum() or c == "_":
            pts.append(cp)
    return pts


def verify_word_matches_re(pts):
    """Guard the assumption that Python's \\w is str.isalnum() or '_'."""
    word = re.compile(r"\w")
    s = set(pts)
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        assert bool(word.fullmatch(chr(cp))) == (cp in s), hex(cp)


def rust_word_points(binary: Path):
    out = subprocess.run([str(binary), "--rs-dump-word"], capture_output=True, text=True, check=True).stdout
    pts = set()
    for line in out.splitlines():
        lo, hi = (int(x, 16) for x in line.split())
        pts.update(range(lo, hi + 1))
    return pts


def case_map():
    """Non-ASCII chars Python's re.I treats as equal to one ASCII letter."""
    allcps = "".join(chr(cp) for cp in range(0x80, 0x110000) if not 0xD800 <= cp <= 0xDFFF)
    result = {}
    for x in "abcdefghijklmnopqrstuvwxyz":
        for flag_pat in (x,):
            for m in re.finditer(flag_pat, allcps, re.I):
                c = m.group()
                prior = result.get(ord(c))
                assert prior in (None, x), (hex(ord(c)), prior, x)
                result[ord(c)] = x
    return result


def fmt_ranges(name, rs):
    body = "".join(f"    (0x{a:x}, 0x{b:x}),\n" for a, b in rs)
    return f"pub static {name}: &[(u32, u32)] = &[\n{body}];\n"


def render(binary: Path) -> str:
    pyw = py_word_points()
    verify_word_matches_re(pyw)
    rsw = rust_word_points(binary)
    pset = set(pyw)
    py_only = sorted(pset - rsw)
    rs_only = sorted(rsw - pset)
    # ASCII is never remapped.
    py_only = [p for p in py_only if p >= 0x80]
    rs_only = [p for p in rs_only if p >= 0x80]
    cm = case_map()
    cm_body = "".join(f"    (0x{cp:x}, '{x}'),\n" for cp, x in sorted(cm.items()))
    return (
        "// @generated by tools/gen_pytables.py -- do not edit by hand.\n"
        f"// python {sys.version.split()[0]}, unicodedata {__import__('unicodedata').unidata_version}\n"
        + fmt_ranges("PY_ONLY_WORD", ranges(py_only))
        + fmt_ranges("RUST_ONLY_WORD", ranges(rs_only))
        + f"pub static CASE_MAP: &[(u32, char)] = &[\n{cm_body}];\n"
    )


if __name__ == "__main__":
    positional = [a for a in sys.argv[1:] if not a.startswith("--")]
    binary = Path(positional[0]) if positional else ROOT / "target" / "release" / "cmdguard-rs"
    text = render(binary)
    if "--check" in sys.argv:
        sys.exit(0 if OUT.read_text() == text else 1)
    OUT.write_text(text)
    print(f"wrote {OUT} ({len(text.splitlines())} lines)")
